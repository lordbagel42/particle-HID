KeyStroke UsLayout::map(char c) const {
    switch (c) {
    case '\n':
        return {(uint8_t)Key::Enter, 0};
    case '\r': // println() sends "\r\n"; type one Enter, not two
        return {0, 0};
    case '\t':
        return {(uint8_t)Key::Tab, 0};
    case '\b':
        return {(uint8_t)Key::Backspace, 0};
    default:
        break;
    }
    const unsigned char u = (unsigned char)c;
    if (u < 0x20 || u > 0x7E) {
        return {0, 0};
    }
    const uint8_t v = kUsAscii[u - 0x20];
    return {(uint8_t)(v & 0x7F), (uint8_t)((v & 0x80) ? Mod::LeftShift : 0)};
}

